"""Vendor the pinned official MAVLink framing library from a Git checkout.

Usage: git clone https://github.com/mavlink/c_library_v2.git build/deps/mavlink-c-library-v2
       git -C build/deps/mavlink-c-library-v2 checkout <PINNED_COMMIT>
       python support/update_mavlink.py build/deps/mavlink-c-library-v2
Only protocol headers and the generated all.xml CRC registry are needed by a
transparent bridge; hundreds of message pack/unpack wrappers are not compiled.
"""
from pathlib import Path
import re
import shutil
import subprocess
import sys

PINNED_COMMIT = "6b4243f0e54b42ddb1e65df7a3a5e8c99d15ec1f"
REPOSITORY = "https://github.com/mavlink/c_library_v2.git"


def main():
    checkout = Path(sys.argv[1]).resolve()
    commit = subprocess.check_output(["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True).strip()
    if commit != PINNED_COMMIT:
        raise SystemExit(f"Expected {PINNED_COMMIT}; checkout is {commit}")
    root = Path(__file__).resolve().parents[1]
    destination = root / "src" / "vendor" / "mavlink"
    destination.mkdir(parents=True, exist_ok=True)
    headers = sorted(checkout.glob("*.h"))
    for header in headers:
        shutil.copyfile(header, destination / header.name)
    dialect = (checkout / "all" / "all.h").read_text(encoding="utf-8")
    registry = re.search(r"^#define MAVLINK_MESSAGE_CRCS .+$", dialect, re.MULTILINE)
    if not registry:
        raise SystemExit("Official all.xml CRC registry missing")
    wrapper = (checkout / "all" / "mavlink.h").read_text(encoding="utf-8")
    wrapper = wrapper.replace('#include "version.h"', "")
    wrapper = wrapper.replace('#include "all.h"', registry.group(0) + '\n#include "protocol.h"')
    (destination / "mavlink_registry.h").write_text(
        "/* Generated by support/update_mavlink.py; upstream wrapper + all.xml CRC registry. */\n" + wrapper,
        encoding="utf-8", newline="\n")
    (destination / "UPSTREAM.md").write_text(
        f"# Official MAVLink C library\n\nSource: {REPOSITORY}\n\nPinned commit: `{commit}`.\n\n"
        "Root protocol headers are copied unchanged from that Git revision. "
        "`mavlink_registry.h` combines the upstream all/mavlink.h configuration with "
        "the all/all.h generated CRC registry, without message-specific wrappers. "
        "Regenerate with `support/update_mavlink.py`; ordinary builds need no network.\n\n"
        "License: generated library MIT; see ../MAVLINK_COPYING.txt.\n",
        encoding="utf-8", newline="\n")
    print(f"Vendored {len(headers)} official headers and all.xml registry at {commit}")


if __name__ == "__main__":
    main()
