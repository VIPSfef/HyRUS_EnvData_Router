"""Real serial transport -> QGC UDP -> serial, using only a private POSIX PTY.

Wire CRCs are independently generated by the existing bit-at-a-time test
generator. Neither a physical serial device nor a production QGC port is used.
"""
import os
from pathlib import Path
import select
import socket
import struct
import subprocess
import sys
import tempfile
import time

from test_mavlink_router import Wire, crc_byte


def packet(version, message, payload, extra, sequence, *, system=1,
           component=1, signature=None):
    """Preserve deliberate MAVLink 2 zero padding and arbitrary signature bytes."""
    if version == 1:
        assert message < 256 and signature is None
        header = bytes((len(payload), sequence, system, component, message))
        magic = b"\xfe"
    else:
        assert version == 2 and (signature is None or len(signature) == 13)
        header = bytes((len(payload), int(signature is not None), 0, sequence,
                        system, component, message & 255,
                        (message >> 8) & 255, message >> 16))
        magic = b"\xfd"
    crc = 0xFFFF
    for byte in header + payload + bytes((extra,)):
        crc = crc_byte(crc, byte)
    return magic + header + payload + struct.pack("<H", crc) + (signature or b"")


class SerialRouter:
    def __init__(self, executable, directory, sink, enabled=True):
        import pty
        import tty

        self.master, self.slave = pty.openpty()
        tty.setraw(self.slave)
        os.set_blocking(self.master, False)
        self.serial = bytearray()
        self.datagrams = []
        self.log = tempfile.TemporaryFile()
        self.sink = sink
        self.child = None
        settings = {
            "url": "-", "stream": "qgc-forward", "session": "qgc-forward",
            "input_mode": "mavlink", "serial_port": os.ttyname(self.slave),
            "auto_scan": 0, "serial_baud": 115200, "udp_enabled": 0,
            "qgc_enabled": int(enabled), "qgc_host": "127.0.0.1",
            "qgc_port": sink.getsockname()[1], "probe_ms": 5000,
            "link_timeout_ms": 1500, "reconnect_ms": 100,
            "refresh_ms": 250, "duration_ms": 15000,
        }
        config = directory / ("enabled.ini" if enabled else "disabled.ini")
        config.write_text("".join(f"{key}={value}\n" for key, value in settings.items()),
                          encoding="utf-8")
        try:
            self.child = subprocess.Popen(
                [str(executable), "--config", str(config), "--interactive"],
                stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=self.log)
            # Explicit serial mode emits a router heartbeat after opening. This
            # avoids losing test bytes to the real transport's initial tcflush.
            self.until(lambda: bool(self.serial), "serial open", timeout=4)
            self.serial.clear()
        except BaseException:
            self.close()
            raise

    def diagnostic(self):
        return os.pread(self.log.fileno(), 65536, 0).decode("utf-8", "replace")

    def pump(self, timeout=.02):
        readable, _, _ = select.select([self.master, self.sink], [], [], timeout)
        if self.master in readable:
            self.serial.extend(os.read(self.master, 65536))
        if self.sink in readable:
            self.datagrams.append(self.sink.recvfrom(65536))

    def until(self, predicate, description, timeout=2):
        deadline = time.monotonic() + timeout
        while not predicate():
            assert self.child.poll() is None, (description, self.child.returncode,
                                               self.diagnostic())
            assert time.monotonic() < deadline, (description, self.datagrams,
                                                 bytes(self.serial).hex(), self.diagnostic())
            self.pump()

    def quiet(self, duration=.2):
        deadline = time.monotonic() + duration
        while time.monotonic() < deadline:
            self.pump(min(.02, deadline - time.monotonic()))

    def write(self, data):
        offset = 0
        while offset < len(data):
            offset += os.write(self.master, data[offset:])

    def expect_packets(self, expected):
        self.until(lambda: len(self.datagrams) >= len(expected), "forwarded UDP packets")
        received = self.datagrams[:len(expected)]
        del self.datagrams[:len(expected)]
        assert [payload for payload, _ in received] == expected, [
            [value.hex() for value in expected], [value.hex() for value, _ in received]]
        peers = {address for _, address in received}
        assert len(peers) == 1, peers
        return peers.pop()

    def close(self):
        if self.child is not None:
            if self.child.poll() is None:
                self.child.terminate()
            self.child.wait(timeout=3)
        for descriptor in (self.master, self.slave):
            os.close(descriptor)
        self.log.close()


def enabled_case(executable, directory, sink):
    router = SerialRouter(executable, directory, sink)
    vehicle = Wire()
    heartbeat_payload = struct.pack("<IBBBBB", 0, 2, 12, 128, 4, 3)
    try:
        first = packet(1, 0, heartbeat_payload, 50, 17)
        corrupted = first[:-1] + bytes((first[-1] ^ 1,))
        router.write(corrupted)
        router.quiet()
        assert not router.datagrams, "CRC-invalid serial frame reached QGC"
        router.write(first)
        peer = router.expect_packets([first])
        assert peer[0] == "127.0.0.1" and peer[1] != sink.getsockname()[1], peer

        # Two packets in one serial read, then headers/payload/CRC split across
        # reads. Zero-padded v2 payloads and signed packets must not be repacked.
        coalesced = [vehicle.navigation(1000, 0), vehicle.named(1000, "temp", 20.0)]
        router.write(b"".join(coalesced))
        assert router.expect_packets(coalesced) == peer
        signed = packet(2, 0, heartbeat_payload, 50, 18,
                        signature=bytes((0, 1, 2, 3, 4, 5, 6, 0xfd, 0xfe, 9, 0, 0, 0)))
        padded = packet(2, 21, b"\x01\x00", 159, 19)
        chunked = signed + padded + vehicle.heartbeat()
        offset = 0
        for count in (1, 2, 7, 1, 11, 3, 2):
            router.write(chunked[offset:offset + count])
            offset += count
            router.quiet(.025)
        router.write(chunked[offset:])
        assert router.expect_packets([signed, padded, chunked[len(signed) + len(padded):]]) == peer

        # A real QGC-style request is returned through the very socket from
        # which the vehicle packet arrived. Router heartbeats may coexist.
        request = packet(2, 21, b"\x01\x01", 159, 91, system=255, component=190)
        sink.sendto(request, peer)
        router.until(lambda: request in router.serial, "QGC request on serial")
        assert router.serial.count(request) == 1
        router.quiet()
        assert not router.datagrams, "QGC reply was echoed back onto UDP"

        # The configured remote address/port is fixed; a different local sender
        # cannot inject commands or replace the selected QGC peer.
        rogue_request = packet(2, 21, b"\x01\x01", 159, 92, system=255, component=190)
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as rogue:
            rogue.bind(("127.0.0.1", 0))
            rogue.sendto(rogue_request, peer)
            router.quiet(.2)
        assert rogue_request not in router.serial, "unconfigured UDP sender reached serial"

        # Invalid return frames are discarded; both valid packets in one QGC
        # datagram retain their original bytes and their stream order.
        invalid = request[:-1] + bytes((request[-1] ^ 1,))
        sink.sendto(invalid, peer)
        router.quiet(.15)
        assert invalid not in router.serial, "CRC-invalid QGC packet reached serial"
        returns = [packet(1, 21, b"\x01\x01", 159, 93, system=255, component=190),
                   packet(2, 21, b"\x01\x01", 159, 94, system=255, component=190)]
        sink.sendto(b"".join(returns), peer)
        router.until(lambda: all(value in router.serial for value in returns), "coalesced QGC requests")
        assert router.serial.index(returns[0]) < router.serial.index(returns[1])

        # With no vehicle traffic, the active serial session expires. Commands
        # sent to its old UDP endpoint must not wait for the next vehicle
        # session. Explicit serial probing may still emit its own heartbeat.
        router.quiet(1.7)
        stale = packet(2, 21, b"\x01\x01", 159, 95, system=255, component=190)
        sink.sendto(stale, peer)
        router.quiet(.2)
        assert stale not in router.serial, "command reached an unselected serial probe"
        recovered = vehicle.heartbeat()
        router.write(recovered)
        router.expect_packets([recovered])
        router.quiet(.15)
        assert stale not in router.serial, "old QGC command leaked into a new serial session"
        print("PASS real serial/QGC bridge: v1/v2 exact bytes, zero padding, signed opaque frames, "
              "chunking, bidirectional requests, peer isolation, CRC rejection, no echo, session isolation")
    finally:
        router.close()


def disabled_case(executable, directory, sink):
    router = SerialRouter(executable, directory, sink, enabled=False)
    try:
        router.write(Wire().heartbeat())
        # Plain log output refreshes once per second even when the interactive
        # screen interval is shorter; wait for observed state, not wall time.
        router.until(lambda: "source status=LOCKED" in router.diagnostic(),
                     "disabled bridge still decodes the serial heartbeat")
        assert not router.datagrams, "disabled QGC bridge emitted UDP"
        assert router.child.poll() is None
        print("PASS disabled QGC bridge leaves serial ingestion running without UDP output")
    finally:
        router.close()


def main():
    if sys.platform == "win32":
        raise SystemExit("This integration test requires a POSIX PTY; run portable bridge tests on Windows.")
    executable = Path(sys.argv[1]).resolve()
    assert executable.is_file(), executable
    with tempfile.TemporaryDirectory(prefix="router-qgc-") as temporary:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sink:
            sink.bind(("127.0.0.1", 0))
            enabled_case(executable, Path(temporary), sink)
            disabled_case(executable, Path(temporary), sink)


if __name__ == "__main__":
    main()
