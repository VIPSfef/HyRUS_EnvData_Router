// Executes the production one-shot protocol and its real result formatter.
#include "SHTC3Probe.hpp"
#include <array>
#include <cstdlib>
#include <cstring>

static unsigned checks = 0;
#define CHECK(condition) do { ++checks; if (!(condition)) { \
			std::fprintf(stderr, "FAIL line %d: %s\n", __LINE__, #condition); std::exit(1); } } while (0)

struct FakeBus {
	std::array<uint16_t, 4> events{};
	std::array<uint32_t, 2> waits{};
	std::array<uint8_t, 3> response{{0x08, 0x07, 0}};
	unsigned calls{0};
	unsigned sleeps{0};
	unsigned wait_calls{0};
	unsigned fail_call{0};
	unsigned fail_wait{0};
	int failure{-6};

	FakeBus() { response[2] = shtc3::Core::crc8(response.data(), 2); }

	int write_command(uint16_t command)
	{
		CHECK(calls < events.size());
		CHECK((command == shtc3::WAKE && calls == 0 && wait_calls == 0)
		      || (command == shtc3::READ_ID && calls == 1 && wait_calls == 1)
		      || (command == shtc3::SLEEP && calls == 3 && wait_calls == 2));
		events[calls++] = command;

		if (command == shtc3::SLEEP) { ++sleeps; }

		CHECK(command == shtc3::WAKE || command == shtc3::READ_ID || command == shtc3::SLEEP);
		return calls == fail_call ? failure : 0;
	}

	int read_response(uint8_t *data, size_t length)
	{
		CHECK(length == response.size());
		CHECK(calls == 2 && wait_calls == 2);
		CHECK(calls < events.size());
		events[calls++] = 0xffff;

		if (calls == fail_call) { return failure; }

		std::memcpy(data, response.data(), length);
		return 0;
	}

	int wait_us(uint32_t duration)
	{
		CHECK(wait_calls < waits.size());
		waits[wait_calls++] = duration;
		CHECK(calls == wait_calls);
		CHECK(duration >= 240);
		return wait_calls == fail_wait ? failure : 0;
	}
};

static void check_complete_order(const FakeBus &bus)
{
	CHECK(bus.calls == 4);
	CHECK(bus.wait_calls == 2);
	CHECK(bus.sleeps == 1);
	CHECK(bus.events[0] == 0x3517);
	CHECK(bus.events[1] == 0xefc8);
	CHECK(bus.events[2] == 0xffff);
	CHECK(bus.events[3] == 0xb098);
	CHECK(bus.waits[0] == 300 && bus.waits[1] == 300);
}

static void check_report(const shtc3_probe::Result &result, const char *text)
{
	char report[224] {};
	const int length = shtc3_probe::format_result(result, report, sizeof(report));
	CHECK(length >= 0 && static_cast<size_t>(length) < sizeof(report));
	CHECK(std::strstr(report, text) != nullptr);
	CHECK(std::strstr(report, result.matched ? "result=MATCH" : "result=UNCONFIRMED") != nullptr);
	const int expected_length = shtc3_probe::format_result(result, nullptr, 0);
	CHECK(expected_length == length);
	char tiny[2] {'X', 'Y'};
	CHECK(shtc3_probe::format_result(result, tiny, sizeof(tiny)) == length);
	CHECK(tiny[1] == '\0');
}

int main()
{
	using namespace shtc3_probe;
	{
		FakeBus bus;
		const Result r = run(bus);
		CHECK(r.matched && r.response_received && r.stage == Stage::Complete);
		CHECK(r.id == 0x0807 && r.crc_received == r.crc_expected);
		CHECK(r.operation_rc == 0 && r.sleep_attempted && r.sleep_rc == 0);
		check_complete_order(bus);
		check_report(r, "stage=COMPLETE id=0x0807");
		check_report(r, "sleep=OK sleep_rc=0");
	}

	// Every IO failure stops immediately; no implicit retries, reset, general
	// call, measurement or sleep to an unidentified device is possible.
	const Stage io_stages[] {Stage::Wake, Stage::ReadIdCommand, Stage::ReadIdResponse};
	const unsigned wait_counts[] {0, 1, 2};

	for (unsigned fail_call = 1; fail_call <= 3; ++fail_call) {
		for (int code : {-1, -6, -110, 1}) {
			FakeBus bus;
			bus.fail_call = fail_call;
			bus.failure = code;
			const Result r = run(bus);
			CHECK(!r.matched && !r.response_received && !r.sleep_attempted);
			CHECK(r.stage == io_stages[fail_call - 1] && r.operation_rc == code);
			CHECK(bus.calls == fail_call && bus.sleeps == 0);
			CHECK(bus.wait_calls == wait_counts[fail_call - 1]);
			check_report(r, "id=unavailable crc_rx=unavailable crc_expected=unavailable");
		}
	}

	for (unsigned fail_wait = 1; fail_wait <= 2; ++fail_wait) {
		FakeBus bus;
		bus.fail_wait = fail_wait;
		bus.failure = -4;
		const Result r = run(bus);
		CHECK(!r.matched && !r.sleep_attempted && r.operation_rc == -4);
		CHECK(r.stage == (fail_wait == 1 ? Stage::WakeWait : Stage::ReadIdWait));
		CHECK(bus.calls == fail_wait && bus.wait_calls == fail_wait && bus.sleeps == 0);
		check_report(r, fail_wait == 1 ? "stage=WAKE_WAIT" : "stage=READ_ID_WAIT");
	}

	{
		FakeBus bus;
		bus.fail_call = 4;
		bus.failure = -6;
		const Result r = run(bus);
		CHECK(r.matched && r.stage == Stage::Complete && r.operation_rc == 0);
		CHECK(r.sleep_attempted && r.sleep_rc == -6);
		check_complete_order(bus);
		check_report(r, "sleep=FAILED sleep_rc=-6");
	}

	// Exhaustive product-ID mask comparison, with valid CRC generated by the
	// production CRC function (the shared driver's independent CRC tests cover
	// its polynomial). A different model at 0x70 receives no SLEEP command.
	unsigned matches = 0;

	for (unsigned id = 0; id <= 0xffff; ++id) {
		FakeBus bus;
		bus.response[0] = static_cast<uint8_t>(id >> 8);
		bus.response[1] = static_cast<uint8_t>(id);
		bus.response[2] = shtc3::Core::crc8(bus.response.data(), 2);
		const Result r = run(bus);
		const bool expected = (id & 0x083fU) == 0x0807U;
		CHECK(r.matched == expected);
		CHECK(r.response_received && r.id == id);
		CHECK(r.crc_received == r.crc_expected);
		CHECK(r.sleep_attempted == expected);
		CHECK(bus.calls == (expected ? 4U : 3U));
		CHECK(bus.sleeps == (expected ? 1U : 0U));
		CHECK(r.stage == (expected ? Stage::Complete : Stage::ProductId));
		matches += expected ? 1U : 0U;

		if (id == 0 || id == 0xffff) { check_report(r, "sleep=NOT_ATTEMPTED"); }
	}

	CHECK(matches == 512);

	// Every possible single-bit corruption of the 24-bit ID response fails
	// CRC, including all CRC-byte errors. No confirmation or SLEEP follows.
	for (unsigned bit = 0; bit < 24; ++bit) {
		FakeBus bus;
		bus.response[bit / 8] ^= static_cast<uint8_t>(1U << (bit % 8));
		const Result r = run(bus);
		CHECK(!r.matched && r.response_received && r.stage == Stage::Crc);
		CHECK(r.crc_received != r.crc_expected && !r.sleep_attempted);
		CHECK(bus.calls == 3 && bus.sleeps == 0);
		check_report(r, "stage=CRC");
	}

	CHECK(std::strcmp(stage_name(static_cast<Stage>(255)), "INVALID") == 0);
	std::printf("SHTC3_PROBE PASS checks=%u result_bytes=%zu max_transfers=4 no_hardware_io\n", checks, sizeof(Result));
	return 0;
}
